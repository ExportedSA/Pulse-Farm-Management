// Writes scripts/baseline.sql: the whole database structure as it is after every migration,
// plus the built-in catalogue, so a brand-new database can be set up in one step.
// run-migrations.ts uses it when the database is empty; later migrations then apply on top.
//
// Only reads from the database. Run it against a database with every migration applied:
//   npx tsx scripts/make-baseline.ts
// Regenerate it (and commit it) whenever you want new databases to start from a later point;
// a stale baseline is still correct, the newer migrations just run after it.
import "dotenv/config";
import fs from "fs";
import path from "path";
import { Pool, neonConfig } from "@neondatabase/serverless";
import ws from "ws";

neonConfig.webSocketConstructor = ws;
const pool = new Pool({ connectionString: process.env.DATABASE_URL });
const out = path.resolve(import.meta.dirname, "baseline.sql");
const migrationsDir = path.resolve(import.meta.dirname, "migrations");

// Shared rows a new farm needs, copied as they are. Only data a migration put there and that
// cites its source; farm data, users and demo rows stay out.
const REFERENCE_DATA = [
  { table: "catalogue_sources", where: "true", order: "id" },
  { table: "input_products", where: "farm_id IS NULL", order: "kind, supplier NULLS FIRST, name, id" },
];
// Neon grants these itself on every new database
const PLATFORM_ROLES = ["cloud_admin", "neon_superuser"];

// Objects that belong to an extension (PostGIS's own tables, views and functions) are created by
// CREATE EXTENSION, not by us
const NOT_EXTENSION = (oid: string) =>
  `NOT EXISTS (SELECT 1 FROM pg_depend d WHERE d.objid = ${oid} AND d.deptype = 'e')`;

const q = async (text: string) => (await pool.query(text)).rows;
const ident = (s: string) => (/^[a-z_][a-z0-9_]*$/.test(s) ? s : `"${s.replace(/"/g, '""')}"`);
const literal = (s: string) => `'${s.replace(/'/g, "''")}'`;

async function main() {
  // The source must be exactly the migrations in the repo, or the baseline would claim the wrong ones
  const applied: string[] = (await q("SELECT name FROM pulse_migrations ORDER BY name")).map((r) => r.name);
  const files = fs.readdirSync(migrationsDir).filter((f) => f.endsWith(".sql")).sort();
  const missing = files.filter((f) => !applied.includes(f));
  const unknown = applied.filter((f) => !files.includes(f));
  if (missing.length || unknown.length) {
    throw new Error(
      `the database doesn't match scripts/migrations (not applied: ${missing.join(", ") || "none"}; ` +
        `not in the repo: ${unknown.join(", ") || "none"}). Run the migrations first.`,
    );
  }

  const sql: string[] = [];
  const add = (...lines: string[]) => sql.push(...lines);

  add(
    "-- Pulse database baseline. Generated by scripts/make-baseline.ts; don't edit by hand.",
    `-- The structure after migrations ${files[0]} to ${files[files.length - 1]}, and the built-in catalogue.`,
    "-- run-migrations.ts applies it to an empty database, in one transaction.",
    "",
    "CREATE EXTENSION IF NOT EXISTS postgis;",
    "",
  );

  // Role used for web requests (see 0025_row_level_security.sql)
  add(
    "DO $$",
    "BEGIN",
    "  IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname = 'pulse_app') THEN",
    "    CREATE ROLE pulse_app NOLOGIN NOBYPASSRLS;",
    "  END IF;",
    "END $$;",
    "GRANT pulse_app TO CURRENT_USER;",
    "GRANT USAGE ON SCHEMA public TO pulse_app;",
    "",
  );

  // Enum types
  const enums = await q(`
    SELECT t.typname, array_agg(e.enumlabel::text ORDER BY e.enumsortorder) AS labels
    FROM pg_type t
    JOIN pg_enum e ON e.enumtypid = t.oid
    WHERE t.typnamespace = 'public'::regnamespace AND ${NOT_EXTENSION("t.oid")}
    GROUP BY t.typname ORDER BY t.typname`);
  add("-- Types");
  for (const e of enums) add(`CREATE TYPE ${ident(e.typname)} AS ENUM (${e.labels.map(literal).join(", ")});`);
  add("");

  // Functions (plpgsql bodies aren't checked against tables until they run, so these can go first)
  const functions = await q(`
    SELECT pg_get_functiondef(p.oid) AS def
    FROM pg_proc p
    WHERE p.pronamespace = 'public'::regnamespace AND ${NOT_EXTENSION("p.oid")}
    ORDER BY p.proname`);
  add("-- Functions");
  for (const f of functions) add(`${f.def.trim()};`, "");

  // Tables
  const tables: string[] = (
    await q(`
      SELECT c.relname FROM pg_class c
      WHERE c.relnamespace = 'public'::regnamespace AND c.relkind = 'r' AND ${NOT_EXTENSION("c.oid")}
        AND c.relname <> 'pulse_migrations' -- the runner makes it; see the end of the file
      ORDER BY c.relname`)
  ).map((r) => r.relname);
  const ours = (r: { relname: string }) => tables.includes(r.relname);
  const otherKinds = await q(`
    SELECT c.relname, c.relkind FROM pg_class c
    WHERE c.relnamespace = 'public'::regnamespace AND c.relkind IN ('v', 'm', 'p', 'S', 'f')
      AND ${NOT_EXTENSION("c.oid")}`);
  if (otherKinds.length) {
    throw new Error(`views, sequences or partitioned tables aren't handled yet: ${otherKinds.map((r) => r.relname).join(", ")}`);
  }

  const columns = await q(`
    SELECT c.relname, a.attname, format_type(a.atttypid, a.atttypmod) AS type, a.attnotnull,
           pg_get_expr(d.adbin, d.adrelid) AS def, a.attgenerated, a.attidentity
    FROM pg_attribute a
    JOIN pg_class c ON c.oid = a.attrelid
    LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
    WHERE c.relnamespace = 'public'::regnamespace AND c.relkind = 'r' AND a.attnum > 0 AND NOT a.attisdropped
    ORDER BY c.relname, a.attnum`);
  const constraints = await q(`
    SELECT c.relname, k.conname, k.contype, pg_get_constraintdef(k.oid) AS def
    FROM pg_constraint k
    JOIN pg_class c ON c.oid = k.conrelid
    WHERE k.connamespace = 'public'::regnamespace AND c.relkind = 'r'
    ORDER BY c.relname, k.contype, k.conname`);
  const unhandled = constraints.filter((k) => !"pucf".includes(k.contype));
  if (unhandled.length) throw new Error(`constraint types not handled: ${unhandled.map((k) => k.conname).join(", ")}`);

  add("-- Tables");
  for (const t of tables) {
    const cols = columns.filter((c) => c.relname === t).map((c) => {
      if (c.attidentity) throw new Error(`identity column ${t}.${c.attname} isn't handled yet`);
      let line = `  ${ident(c.attname)} ${c.type}`;
      if (c.attgenerated === "s") line += ` GENERATED ALWAYS AS (${c.def}) STORED`;
      else if (c.def != null) line += ` DEFAULT ${c.def}`;
      if (c.attnotnull) line += " NOT NULL";
      return line;
    });
    // Keys and checks go with the table; foreign keys after every table exists
    const own = constraints
      .filter((k) => k.relname === t && k.contype !== "f")
      .map((k) => `  CONSTRAINT ${ident(k.conname)} ${k.def}`);
    add(`CREATE TABLE ${ident(t)} (`, [...cols, ...own].join(",\n"), ");", "");
  }

  add("-- Foreign keys");
  for (const k of constraints.filter((k) => k.contype === "f" && ours(k))) {
    add(`ALTER TABLE ${ident(k.relname)} ADD CONSTRAINT ${ident(k.conname)} ${k.def};`);
  }
  add("");

  // Indexes that aren't already made by a primary key or unique constraint
  const indexes = await q(`
    SELECT c.relname, pg_get_indexdef(i.indexrelid) AS def
    FROM pg_index i
    JOIN pg_class c ON c.oid = i.indrelid
    JOIN pg_class ic ON ic.oid = i.indexrelid
    WHERE c.relnamespace = 'public'::regnamespace AND c.relkind = 'r' AND ${NOT_EXTENSION("c.oid")}
      AND NOT EXISTS (SELECT 1 FROM pg_constraint k WHERE k.conindid = i.indexrelid AND k.conrelid = i.indrelid)
    ORDER BY c.relname, ic.relname`);
  add("-- Indexes");
  for (const i of indexes.filter(ours)) add(`${i.def};`);
  add("");

  // Built-in rows, before the triggers so they go in as they were
  add("-- Built-in catalogue");
  for (const r of REFERENCE_DATA) {
    const rows: string[] = (
      await q(`SELECT row_to_json(t)::text AS j FROM ${ident(r.table)} t WHERE ${r.where} ORDER BY ${r.order}`)
    ).map((x) => x.j);
    if (!rows.length) continue;
    const body = `[\n${rows.join(",\n")}\n]`;
    if (body.includes("$pulse$")) throw new Error(`${r.table} data contains the quoting marker`);
    add(
      `INSERT INTO ${ident(r.table)} SELECT * FROM json_populate_recordset(NULL::${ident(r.table)}, $pulse$${body}$pulse$);`,
      "",
    );
  }

  const triggers = await q(`
    SELECT c.relname, pg_get_triggerdef(tg.oid) AS def
    FROM pg_trigger tg
    JOIN pg_class c ON c.oid = tg.tgrelid
    WHERE c.relnamespace = 'public'::regnamespace AND NOT tg.tgisinternal AND ${NOT_EXTENSION("c.oid")}
    ORDER BY c.relname, tg.tgname`);
  add("-- Triggers");
  for (const t of triggers.filter(ours)) add(`${t.def};`);
  add("");

  // Row-level security
  const rls = await q(`
    SELECT c.relname, c.relforcerowsecurity FROM pg_class c
    WHERE c.relnamespace = 'public'::regnamespace AND c.relkind = 'r' AND c.relrowsecurity
    ORDER BY c.relname`);
  const policies = await q(`
    SELECT c.relname, p.polname, p.polpermissive, p.polcmd,
           ARRAY(SELECT CASE WHEN r = 0 THEN 'PUBLIC' ELSE quote_ident(pg_get_userbyid(r)) END
                 FROM unnest(p.polroles) r) AS roles,
           pg_get_expr(p.polqual, p.polrelid) AS qual, pg_get_expr(p.polwithcheck, p.polrelid) AS withcheck
    FROM pg_policy p
    JOIN pg_class c ON c.oid = p.polrelid
    WHERE c.relnamespace = 'public'::regnamespace
    ORDER BY c.relname, p.polname`);
  const cmd: Record<string, string> = { r: "SELECT", a: "INSERT", w: "UPDATE", d: "DELETE", "*": "ALL" };
  add("-- Row-level security");
  for (const t of rls.filter(ours)) {
    add(`ALTER TABLE ${ident(t.relname)} ENABLE ROW LEVEL SECURITY;`);
    if (t.relforcerowsecurity) add(`ALTER TABLE ${ident(t.relname)} FORCE ROW LEVEL SECURITY;`);
  }
  for (const p of policies.filter(ours)) {
    let line = `CREATE POLICY ${ident(p.polname)} ON ${ident(p.relname)}`;
    if (!p.polpermissive) line += " AS RESTRICTIVE";
    line += ` FOR ${cmd[p.polcmd]} TO ${p.roles.join(", ")}`;
    if (p.qual) line += ` USING (${p.qual})`;
    if (p.withcheck) line += ` WITH CHECK (${p.withcheck})`;
    add(`${line};`);
  }
  add("");

  // Grants on tables to anyone besides the owner and Neon's own roles
  const grants = await q(`
    SELECT c.relname,
           CASE WHEN a.grantee = 0 THEN 'PUBLIC' ELSE quote_ident(pg_get_userbyid(a.grantee)) END AS grantee,
           string_agg(a.privilege_type, ', ' ORDER BY a.privilege_type) AS privileges
    FROM pg_class c, aclexplode(c.relacl) a
    WHERE c.relnamespace = 'public'::regnamespace AND c.relkind = 'r' AND ${NOT_EXTENSION("c.oid")}
      AND a.grantee <> c.relowner
      AND (a.grantee = 0 OR pg_get_userbyid(a.grantee) <> ALL (ARRAY[${PLATFORM_ROLES.map(literal).join(", ")}]))
    GROUP BY c.relname, a.grantee
    ORDER BY c.relname, 2`);
  add("-- Grants");
  for (const g of grants.filter(ours)) add(`GRANT ${g.privileges} ON ${ident(g.relname)} TO ${g.grantee};`);
  // Tables and sequences made by later migrations get the same access (as 0025 sets up)
  const defaults = await q(`
    SELECT d.defaclobjtype, quote_ident(pg_get_userbyid(a.grantee)) AS grantee,
           string_agg(a.privilege_type, ', ' ORDER BY a.privilege_type) AS privileges
    FROM pg_default_acl d, aclexplode(d.defaclacl) a
    WHERE d.defaclrole = (SELECT oid FROM pg_roles WHERE rolname = current_user)
      AND d.defaclnamespace IN (0, 'public'::regnamespace)
    GROUP BY d.defaclobjtype, a.grantee
    ORDER BY 1, 2`);
  const objects: Record<string, string> = { r: "TABLES", S: "SEQUENCES", f: "FUNCTIONS", T: "TYPES" };
  for (const d of defaults) {
    add(`ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT ${d.privileges} ON ${objects[d.defaclobjtype]} TO ${d.grantee};`);
  }
  add("");

  // Which migrations this already includes, so the runner doesn't apply them again
  add(
    "-- Migrations included",
    "CREATE TABLE IF NOT EXISTS pulse_migrations (",
    "  name text PRIMARY KEY,",
    "  applied_at timestamp NOT NULL DEFAULT now()",
    ");",
    `INSERT INTO pulse_migrations (name) VALUES\n${files.map((f) => `  (${literal(f)})`).join(",\n")};`,
    "",
  );

  fs.writeFileSync(out, sql.join("\n"));
  console.log(
    `wrote ${path.relative(process.cwd(), out)}: ${tables.length} tables, ${enums.length} types, ` +
      `${indexes.length} indexes, ${triggers.length} triggers, ${policies.length} policies, through ${files[files.length - 1]}`,
  );
}

main()
  .catch((err) => {
    console.error(err.message ?? err);
    process.exitCode = 1;
  })
  .finally(() => pool.end());
